const { contextBridge, ipcRenderer } = require('electron');

// 画面側から使える窓口。ここに出したものだけが renderer から見える
contextBridge.exposeInMainWorld('anki', {
  call: (method, params) => ipcRenderer.invoke('anki', method, params),
  mediaDir: () => ipcRenderer.invoke('mediaDir'),
  pickMedia: () => ipcRenderer.invoke('pickMedia'),
  settingsAll: () => ipcRenderer.invoke('settings:all'),
  aiAsk: (payload) => ipcRenderer.invoke('ai:ask', payload),
  aiCancel: () => ipcRenderer.invoke('ai:cancel'),
  clipboardText: () => ipcRenderer.invoke('clipboard:text'),
  readFileUris: (uris) => ipcRenderer.invoke('files:readUris', uris),
  aiList: () => ipcRenderer.invoke('ai:list'),
  aiSave: (pv) => ipcRenderer.invoke('ai:save', pv),
  aiRemove: (id) => ipcRenderer.invoke('ai:remove', id),
  aiUse: (id, model) => ipcRenderer.invoke('ai:use', id, model),
  aiTest: (id) => ipcRenderer.invoke('ai:test', id),
  aiModels: (id) => ipcRenderer.invoke('ai:models', id),
  aiPickFiles: () => ipcRenderer.invoke('ai:pickFiles'),
  aiFetchUrl: (url) => ipcRenderer.invoke('ai:fetchUrl', url),
  editsAll: () => ipcRenderer.invoke('edits:all'),
  trashAll: () => ipcRenderer.invoke('trash:all'),
  trashSave: (list) => ipcRenderer.invoke('trash:save', list),
  backupPick: () => ipcRenderer.invoke('backup:pick'),
  backupNow: (dir, keep) => ipcRenderer.invoke('backup:now', dir, keep),
  backupList: (dir) => ipcRenderer.invoke('backup:list', dir),
  collectionPath: () => ipcRenderer.invoke('collection:path'),
  previewPreload: () => ipcRenderer.invoke('preview:preload'),
  previewPage: (html) => ipcRenderer.invoke('preview:page', html),
  cssPath: () => ipcRenderer.invoke('css:path'),
  openDevTools: () => ipcRenderer.invoke('devtools:open'),
  cssRead: () => ipcRenderer.invoke('css:read'),
  cssReveal: () => ipcRenderer.invoke('css:reveal'),
  onCssChanged: (fn) => ipcRenderer.on('css-changed', () => fn()),
  mark: (name) => ipcRenderer.invoke('mark', name),
  typingLog: (line) => ipcRenderer.invoke('typing:log', line),
  typeText: (text, gapMs) => ipcRenderer.invoke('input:type', text, gapMs),
  rightClick: (x, y) => ipcRenderer.invoke('input:rightClick', x, y),
  profileType: (text, gapMs) => ipcRenderer.invoke('profile:type', text, gapMs),
  editsSave: (all) => ipcRenderer.invoke('edits:save', all),
  onConfirmClose: (fn) => ipcRenderer.on('confirm-close', () => fn()),
  closeNow: () => ipcRenderer.invoke('window:closeNow'),
  setWindowMaxWidth: (width) => ipcRenderer.invoke('window:maxWidth', width),
  adjustWindowLeft: (delta) => ipcRenderer.invoke('window:adjustLeft', delta),
  settingsSet: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  ankiStatus: () => ipcRenderer.invoke('anki:status'),
  ankiSetProfile: (name) => ipcRenderer.invoke('anki:setProfile', name),
  ankiLaunch: () => ipcRenderer.invoke('anki:launch'),
  onWindowBlur: (fn) => ipcRenderer.on('window-blur', () => fn()),
  onWindowFocus: (fn) => ipcRenderer.on('window-focus', () => fn()),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, action) => fn(action)),
  menuKeys: (keys) => ipcRenderer.invoke('menu:keys', keys),
});
